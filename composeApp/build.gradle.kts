/**
 * Signing material for the upload key. It is a per-deployment secret, so nothing about it lives in
 * the repository: values come from the environment (that is what CI has) or from a gitignored
 * `keystore.properties` next to this build script (that is what a person building a signed binary
 * by hand has). With neither, `release` stays unsigned and still builds — a clone must not need a
 * keystore to compile.
 */
val keystoreProperties = layout.projectDirectory.file("keystore.properties").asFile
    .takeIf { it.exists() }
    ?.let { file -> Properties().apply { file.inputStream().use { load(it) } } }

fun signingValue(env: String, property: String): String? =
    providers.environmentVariable(env).orNull?.ifEmpty { null }
        ?: keystoreProperties?.getProperty(property)?.ifEmpty { null }

val keystorePath = signingValue("ANDROID_KEYSTORE_FILE", "storeFile")

android {
    namespace = "cx.m42.unitool"
    compileSdk = libs.versions.androidCompileSdk.get().toInt()

    defaultConfig {
        applicationId = "cx.m42.unitool"
        minSdk = libs.versions.androidMinSdk.get().toInt()
        targetSdk = libs.versions.androidTargetSdk.get().toInt()
        // Play refuses an upload whose versionCode it has already seen, so the number comes from
        // something that only grows and is not edited by hand: the CI run number. A local build
        // keeps 1 — it never reaches Play.
        versionCode = providers.environmentVariable("ANDROID_VERSION_CODE").orNull?.toIntOrNull() ?: 1
        versionName = appVersionName
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_11
        targetCompatibility = JavaVersion.VERSION_11
    }

    signingConfigs {
        // Declared only when the material is actually there; referencing a signingConfig whose
        // storeFile does not exist fails the build at execution time rather than falling back.
        if (keystorePath != null) {
            create("release") {
                storeFile = file(keystorePath)
                storePassword = signingValue("ANDROID_KEYSTORE_PASSWORD", "storePassword")
                keyAlias = signingValue("ANDROID_KEY_ALIAS", "keyAlias")
                keyPassword = signingValue("ANDROID_KEY_PASSWORD", "keyPassword")
                // v1 is the old JAR signature, which only API 23 and below still reads; minSdk
                // here is 24, so it is dead weight in every APK it would go into. v2 is what
                // verifies the archive, and v3 is what would let this key be rotated later
                // without every installed copy refusing the update.
                enableV1Signing = false
                enableV2Signing = true
                enableV3Signing = true
            }
        }
    }

    buildTypes {
        getByName("release") {
            // R8, in the shrink-and-obfuscate configuration Play expects of a release. Compose
            // pulls in a large dependency graph of which this app uses a sliver, so the shrink is
            // most of the download size; see proguard-rules.pro for why so little has to be kept
            // by hand.
            isMinifyEnabled = true
            // Only safe because every resource this app has is referenced statically — the icon
            // and the themes from the manifest, nothing by name at runtime. A resource fetched
            // via getIdentifier() would have to be listed in a keep.xml before this could stay on.
            isShrinkResources = true
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro",
            )
            // Absent keystore ⇒ an unsigned release artifact, which still builds.
            signingConfig = signingConfigs.findByName("release")
        }
    }

    bundle {
        // Off, because this app does not read its strings out of Android resources: they are
        // Kotlin tables in the dex, and Settings switches between them at runtime. Play's
        // per-language splits would install only the device's language while the in-app picker
        // went on offering both — a split that cannot serve the feature it would be splitting.
        language {
            enableSplit = false
        }
    }

    packaging {
        resources {
            // Duplicate metadata from the several coroutines/Compose artifacts that each carry a
            // copy. Harmless, but they are the difference between a clean packaging step and a
            // build that fails on the first dependency bump.
            excludes += "/META-INF/{AL2.0,LGPL2.1}"
            excludes += "/META-INF/versions/9/previous-compilation-data.bin"
        }
    }
}

