#!/usr/bin/env bash
#
# Refreshes the Public Suffix List snapshot the Passwords app matches sites by (passwords-browser
# D561): downloads publicsuffix.org's list, keeps the rules of both sections (ICANN and PRIVATE —
# without PRIVATE, a.github.io and b.github.io would be "one site"), writes every label in its
# ASCII (xn--) form, since that is how a browser sends an origin, and regenerates
# apps/passwords/src/commonMain/kotlin/cx/m42/apps/passwords/PublicSuffixData.kt.
#
# Usage: scripts/update-psl.sh [path-to-a-downloaded-list]
set -euo pipefail
cd "$(dirname "$0")/.."
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
if [ $# -ge 1 ]; then cp "$1" "$work/psl.dat"; else curl -fsSL -o "$work/psl.dat" https://publicsuffix.org/list/public_suffix_list.dat; fi
python3 -I - "$work/psl.dat" apps/passwords/src/commonMain/kotlin/cx/m42/apps/passwords/PublicSuffixData.kt <<'PY'
import sys
src, out = sys.argv[1], sys.argv[2]
text = open(src, encoding="utf-8").read()
version = next((l.split(":", 1)[1].strip() for l in text.splitlines() if l.startswith("// VERSION:")), "unknown")
commit = next((l.split(":", 1)[1].strip() for l in text.splitlines() if l.startswith("// COMMIT:")), "unknown")

def ascii_label(label):
    if label in ("*",) or label.isascii():
        return label.lower()
    return "xn--" + label.lower().encode("punycode").decode("ascii")

rules = []
for line in text.splitlines():
    line = line.strip()
    if not line or line.startswith("//"):
        continue
    rule = line.split()[0]
    bang = rule.startswith("!")
    body = rule[1:] if bang else rule
    rules.append(("!" if bang else "") + ".".join(ascii_label(l) for l in body.split(".")))
rules = sorted(set(rules))
chunks, current = [], []
size = 0
for r in rules:
    if size + len(r) + 1 > 30000:
        chunks.append("\n".join(current)); current, size = [], 0
    current.append(r); size += len(r) + 1
if current: chunks.append("\n".join(current))
with open(out, "w", encoding="utf-8") as f:
    f.write("package cx.m42.apps.passwords\n\n")
    f.write("// Generated by scripts/update-psl.sh from publicsuffix.org — do not edit by hand.\n\n")
    f.write("/**\n * The Public Suffix List (both sections, every label in its xn-- form), for matching an entry to\n")
    f.write(" * the site a computer asks for by eTLD+1 (passwords-browser D543, D561). Mozilla Public License 2.0.\n */\n")
    f.write("internal object PublicSuffixData {\n")
    f.write('    const val VERSION: String = "%s"\n' % version)
    f.write('    const val COMMIT: String = "%s"\n\n' % commit)
    f.write("    /** Rules, one per line: `com`, `*.ck`, `!www.ck`. In pieces, because a JVM string constant holds 64 KiB. */\n")
    f.write("    val CHUNKS: Array<String> = arrayOf(\n")
    for c in chunks:
        f.write('        "' + c.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace("\n", "\\n") + '",\n')
    f.write("    )\n}\n")
print(f"{len(rules)} rules in {len(chunks)} chunks, version {version}")
PY
